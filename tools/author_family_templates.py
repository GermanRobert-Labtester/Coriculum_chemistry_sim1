#!/usr/bin/env python3
"""Freeze the 28 N20 family templates into ``data/family_templates/``.

The authored content lives in ``tools/n20_content.py``. This script is the
*provenance* of the template data; the JSON files it writes are the artifact.
Re-running the script must reproduce the same bytes, so the writer is
canonical: sorted keys, no whitespace, UTF-8, and whole numbers kept whole.

Normalising whole floats to integers is not cosmetic. The Python authoring
twin and the JavaScript runtime twin both serialise the templates through
their own canonical writers; if a value arrived as ``3.0`` in one language and
``3`` in the other, the two canonical texts would differ and the cross-language
byte-identity proof would fail for a reason that has nothing to do with the
chemistry. Genuinely fractional values (four rubric criteria at 0.75 points)
stay fractional and are written with their exact decimal text.

Usage:
    python3 tools/author_family_templates.py [--repo-root .] [--check]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

import n20_content  # noqa: E402
from variant_engine import (  # noqa: E402
    TEMPLATE_ISLAND_ID,
    VariantEngineError,
    canonical_bytes,
    template_digest,
)

TEMPLATE_DIR = Path('data/family_templates')
RUNTIME_ASSET = Path('src/variant-templates.js')

TEMPLATE_NOTE = (
    'PROPOSED training policy (N20). Ģimeņu skaits, variantu skaits, punktu '
    'svarība un minūšu budžets nav oficiāla eksāmena fakts.'
)

RUNTIME_ASSET_HEADER = """/* N20 family templates — runtime asset for the variant engine.
 *
 * GENERATED FILE. The authority is the frozen template data in
 * `data/family_templates/topic1.json` … `topic7.json`, written by
 * `tools/author_family_templates.py`. Do not edit this file by hand: re-run
 * the authoring tool instead.
 *
 * The asset exists so that the runtime twin (`src/variant-engine.js`) can
 * instantiate the *ephemeral* retry path without a network fetch and without
 * embedding 300 KiB of templates in the artifact. It ships from `src/` and is
 * NOT inlined into `output/simulator.html`, exactly like the N17/N18/N19
 * engine modules; N31 owns the inline / lazy-load / re-budget decision.
 *
 * The `families` value is the canonical JSON text of the template array.
 * Canonical JSON is a subset of JavaScript expression syntax, so the array is
 * embedded verbatim: the bytes the twin digests are the bytes the authoring
 * twin digests.
 */
(function (root) {
  'use strict';
  root.SimFamilyTemplates = {
    island_id: 'sim-family-templates',
    template_digest: '%s',
    families: %s
  };
  if (typeof module !== 'undefined' && module.exports) { module.exports = root.SimFamilyTemplates; }
})(typeof globalThis !== 'undefined' ? globalThis : this);
"""


def normalise_numbers(value: Any) -> Any:
    """Recursively replace whole floats with integers."""
    if isinstance(value, bool):
        return value
    if isinstance(value, float):
        return int(value) if value == int(value) else value
    if isinstance(value, dict):
        return {k: normalise_numbers(v) for k, v in value.items()}
    if isinstance(value, list):
        return [normalise_numbers(v) for v in value]
    return value


def build_templates() -> list[dict[str, Any]]:
    """Assemble the 28 family templates in family order."""
    families = normalise_numbers(n20_content.ALL_FAMILIES)
    exemptions = getattr(n20_content, 'EXEMPTIONS', {})
    for family in families:
        family['policy_label'] = n20_content.ALL_FAMILIES[0]['policy_label']
        family['template_note_lv'] = TEMPLATE_NOTE
        for variant in family['variants']:
            variant['seed_key'] = f"{family['family_id']}-{variant['variant_id']}"
            variant.setdefault('seed_algorithm', 'fnv1a64-utf8-v1')
            key = f"{family['family_id']}-{variant['variant_id']}"
            if key in exemptions:
                variant['leak_scan_exemption'] = dict(exemptions[key])
            else:
                variant['leak_scan_exemption'] = None
    families.sort(key=lambda f: f['family_id'])
    return families


def group_by_topic(families: list[dict[str, Any]]) -> dict[int, list[dict[str, Any]]]:
    grouped: dict[int, list[dict[str, Any]]] = {}
    for family in families:
        grouped.setdefault(int(family['topic']), []).append(family)
    return grouped


def write_templates(repo_root: Path, check_only: bool) -> dict[str, Any]:
    families = build_templates()
    grouped = group_by_topic(families)
    out_dir = repo_root / TEMPLATE_DIR
    written: list[str] = []
    mismatched: list[str] = []
    for topic in sorted(grouped):
        payload = {
            'island_id': TEMPLATE_ISLAND_ID,
            'topic': topic,
            'families': grouped[topic],
        }
        data = canonical_bytes(payload) + b'\n'
        path = out_dir / f'topic{topic}.json'
        if check_only:
            if not path.exists() or path.read_bytes() != data:
                mismatched.append(str(path.relative_to(repo_root)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        written.append(str(path.relative_to(repo_root)))
    return {
        'families': len(families),
        'variants': sum(len(f['variants']) for f in families),
        'files': written or sorted(
            str(p.relative_to(repo_root)) for p in out_dir.glob('topic*.json')),
        'mismatched': mismatched,
        'template_digest': template_digest(families),
    }


def write_runtime_asset(repo_root: Path, families: list[dict[str, Any]],
                        check_only: bool) -> dict[str, Any]:
    """Emit the runtime template asset consumed by the JavaScript twin.

    The asset carries the same families the JSON files carry, in the same
    order and with the same canonical serialisation, so both languages digest
    the same template set. The digest in the header is the authority's digest
    of the same content, which lets the harness compare the two without
    re-serialising anything.
    """
    digest = template_digest(families)
    families_text = canonical_bytes(families).decode('utf-8')
    # U+2028 / U+2029 are line terminators in JavaScript but legal raw
    # characters in JSON, so they would break the generated literal. The
    # Latvian content does not contain them; the guard keeps that a fact.
    for forbidden in ('\u2028', '\u2029', '\u0000'):
        if forbidden in families_text:
            raise ValueError(f'Runtime asset cannot contain U+{ord(forbidden):04X}.')
    text = RUNTIME_ASSET_HEADER % (digest, families_text)
    path = repo_root / RUNTIME_ASSET
    if check_only:
        mismatched = not path.exists() or path.read_text(encoding='utf-8') != text
        return {'path': str(RUNTIME_ASSET), 'mismatched': mismatched,
                'template_digest': digest, 'bytes': len(text.encode('utf-8'))}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')
    return {'path': str(RUNTIME_ASSET), 'mismatched': False,
            'template_digest': digest, 'bytes': len(text.encode('utf-8'))}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description='Freeze the N20 family templates.')
    parser.add_argument('--repo-root', default='.')
    parser.add_argument('--check', action='store_true',
                        help='Verify the frozen files match the authored content.')
    args = parser.parse_args(argv)
    repo_root = Path(args.repo_root).resolve()
    try:
        report = write_templates(repo_root, args.check)
        report['runtime_asset'] = write_runtime_asset(
            repo_root, build_templates(), args.check)
    except VariantEngineError as error:
        print(str(error), file=sys.stderr)
        return 2
    report['mode'] = 'check' if args.check else 'write'
    print(json.dumps(report, ensure_ascii=False, indent=2))
    if args.check and (report['mismatched'] or report['runtime_asset']['mismatched']):
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
