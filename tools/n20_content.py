def src(topic: int, locator: str, status: str = 'text-verified') -> dict:
    path, sha = SOURCES[topic]
    return {'path': path, 'sha256': sha, 'locator': locator, 'claim_status': status}


# ------------------------------------------------------------------ builders

def P(pid, label, lo, hi, step, decimals, unit='', disp=None):
    """A drawn integer parameter (base-unit value = drawn / 10**decimals)."""
    return {'param_id': pid, 'label_lv': label, 'kind': 'int', 'min': lo, 'max': hi,
            'step': step, 'decimals': decimals, 'unit': unit,
            'display_decimals': decimals if disp is None else disp}


def C(pid, label, ref, decimals, unit='', disp=None):
    """A constant resolved by reference from the conventions island."""
    return {'param_id': pid, 'label_lv': label, 'kind': 'constant', 'conventions_ref': ref,
            'decimals': decimals, 'unit': unit,
            'display_decimals': decimals if disp is None else disp}


def F(pid, label, value, note_lv, decimals=0, unit=''):
    """An authored fixed factor stated by the task (stoichiometry or counting)."""
    return {'param_id': pid, 'label_lv': label, 'kind': 'fixed', 'value': value,
            'decimals': decimals, 'unit': unit, 'display_decimals': decimals,
            'note_lv': note_lv}


def D(vid, op, args, unit='', disp=6, role='intermediate', tol=None, path=None, n17=None):
    """A derived value produced by an exact fixed-point recipe."""
    spec = {'value_id': vid, 'op': op, 'args': list(args), 'unit': unit,
            'display_decimals': disp, 'role': role}
    if tol:
        spec['tolerance_class'] = tol
    if path:
        spec['engine_path'] = path
    if n17:
        spec['n17_recipe'] = n17
    return spec


def R(cid, points, grading='auto', binding='N17-numeric', depends=None, carry=False):
    return {'criterion_id': cid, 'points': points, 'grading': grading,
            'engine_binding': binding, 'depends_on': list(depends or []),
            'carry_forward': carry}


def V(variant_id, type_id, spec_lv, stem_lv, params, derived, payload, rubric,
      difficulty='application', minutes=5.0, mc=None, feedback=None, givens=None,
      sources=None, review=None, types=None, exempt=None):
    return {
        'variant_id': variant_id,
        'type_id': type_id,
        'type_ids': list(types or [type_id]),
        'spec_lv': spec_lv,
        'difficulty': difficulty,
        'time_minutes': minutes,
        'misconception_signatures': list(mc or []),
        'stem_lv': stem_lv,
        'feedback_lv': feedback or FEEDBACK_DEFAULT,
        'givens_static': dict(givens or {}),
        'parameters': list(params),
        'derived': list(derived),
        'payload': payload,
        'rubric': list(rubric),
        'source_refs': list(sources or []),
        'review': dict(review or REVIEW_DEFAULT),
        'leak_scan_exemption': dict(exempt) if exempt else None,
    }


def FAM(family_id, topic, title_lv, point_weight, slot_id, type_mix, outcome_ids, variants):
    return {
        'family_id': family_id,
        'topic': topic,
        'title_lv': title_lv,
        'point_weight': point_weight,
        'slot_id': slot_id,
        'type_mix': list(type_mix),
        'outcome_ids': list(outcome_ids),
        'policy_label': 'PROPOSED training policy (N20). Nav oficiāls eksāmena apstiprinājums.',
        'variants': list(variants),
    }


