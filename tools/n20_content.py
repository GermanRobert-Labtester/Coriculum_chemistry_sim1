#!/usr/bin/env python3
"""N20 authored content for the 28 family templates.

This module holds the *authored* content of the 28 practice families: the
Latvian stems, the declared parameter ranges, the derivation recipes, the
response payloads and the rubrics. ``tools/author_family_templates.py`` writes
it out as the frozen template data in ``data/family_templates/``.

Authoring rules that this file obeys:

* Every numeric quantity a learner sees is either a *drawn* parameter (a
  declared integer range inside the family's declared limits), an *authored
  fixed* factor (a stoichiometric or counting datum stated in the task), or a
  *constant* resolved by reference from ``data/conventions.json`` (molar
  masses, atomic masses, unit-conversion factors, standard potentials). No
  physical constant is copied by value into the templates.
* Every derived value is produced by an exact fixed-point recipe, so the
  Python authoring twin and the JavaScript runtime twin emit identical bytes.
* Every numeric answer names its tolerance class, its unit and its expected
  significant figures, and the chosen unit keeps the declared absolute
  tolerance of that class meaningful for the answer's magnitude.
* Every percentage names its basis (m/m, m/V or V/V).
* Method-class instances carry self-assessed criteria: the frozen N17 engine
  denies machine criteria on the ``method`` payload class, so nothing here
  claims a machine grade it cannot deliver.
* Nothing here claims official examination status; the templates are training
  material with a PROPOSED training policy (28 families x 4 variants).
"""
