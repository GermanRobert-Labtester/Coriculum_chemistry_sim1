# ------------------------------------------------------------ payload builders

def num(answer, unit, tol, sig, display, fields, givens_from=None, substeps=None, scale_spec=None,
        round_mode=None, round_digits=None):
    spec = {'class': 'numeric', 'answer': answer, 'unit': unit, 'tolerance_class': tol,
            'sig_figs': sig, 'display_lv': display, 'input_fields': fields,
            'givens_from': list(givens_from or [])}
    if round_mode:
        spec['round_mode'] = round_mode
        spec['round_digits'] = int(round_digits if round_digits is not None else sig)
    if substeps:
        spec['substeps'] = substeps
    if scale_spec:
        spec['scale_spec'] = scale_spec
        # A reading is reported to the instrument's precision, not to a number
        # of significant figures, so the payload declares the rounding mode.
        reported = scale_spec.get('reported_decimals')
        if reported is not None:
            spec['round_mode'] = 'decimal_places'
            spec['round_digits'] = int(reported)
    return spec


def opts(options, correct, distractors=None, justify=False, justification=None, givens_from=None):
    spec = {'class': 'option_select', 'options': [{'option_id': o[0], 'text_lv': o[1]} for o in options],
            'correct_ids': list(correct),
            'distractors': [{'option_id': d[0], 'rationale_lv': d[1]} for d in (distractors or [])],
            'requires_justification': justify,
            'givens_from': list(givens_from or [])}
    if justification:
        spec['justification_prompt_lv'] = justification
    return spec


def order(items, correct_order, explain, partial=None, givens_from=None):
    spec = {'class': 'ordering', 'items': [{'item_id': i[0], 'text_lv': i[1]} for i in items],
            'correct_order': list(correct_order),
            'explanation_prompt_lv': explain,
            'givens_from': list(givens_from or [])}
    if partial:
        spec['partial_order_rules'] = partial
    return spec


def match(left, right, pairs, givens_from=None):
    return {'class': 'matching',
            'left_items': [{'id': i[0], 'text_lv': i[1]} for i in left],
            'right_items': [{'id': i[0], 'text_lv': i[1]} for i in right],
            'correct_pairs': [{'left_id': a, 'right_id': b} for a, b in pairs],
            'givens_from': list(givens_from or [])}


def graph(mode, xaxis, yaxis, points, readout, givens_from=None):
    return {'class': 'graph', 'mode': mode,
            'x_axis': {'label_lv': xaxis[0], 'unit': xaxis[1]},
            'y_axis': {'label_lv': yaxis[0], 'unit': yaxis[1]},
            'points': [{'x': p[0], 'y': p[1]} for p in points],
            'target_readout': {'quantity': readout[0], 'answer': readout[1],
                               'unit': readout[2], 'tolerance_class': readout[3]},
            'givens_from': list(givens_from or [])}


def meth(steps, explain, summary, species=None, medium=None, givens_from=None):
    spec = {'class': 'method',
            'steps': [{'step_id': s[0], 'prompt_lv': s[1], 'expected': s[2]} for s in steps],
            'explanation_prompt_lv': explain,
            'expected_summary_lv': summary,
            'givens_from': list(givens_from or [])}
    if species:
        spec['species_list'] = list(species)
    if medium:
        spec['medium'] = medium
    return spec


